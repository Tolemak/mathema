export const dictionaries: Record<Lang, Record<MessageKey, string>> = { pl, en };

export type MessageVars = Record<string, string | number>;

/** Looks a message up and fills `{name}` placeholders. */
export function translate(lang: Lang, key: MessageKey, vars?: MessageVars): string {
  const template = dictionaries[lang][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function isLang(value: unknown): value is Lang {
  return value === 'pl' || value === 'en';
}

/** Returns the entry for a dynamic key such as `category.<id>`, or the fallback when there is none. */
export function lookup(lang: Lang, prefix: string, id: string, fallback: string): string {
  const key = `${prefix}.${id}`;
  return key in pl ? dictionaries[lang][key as MessageKey] : fallback;
}
